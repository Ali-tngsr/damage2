def create_base_geometry_2d(model_name, part_name, L, total_thickness):
    """
    ساخت پارت پایه به صورت 2D planar (سطح مقطع).
    X = طول نمونه, Y = ضخامت
    """
    # اگر مدل وجود دارد، حذف کن
    model_keys = mdb.models.keys()
    if model_name in model_keys:
        del mdb.models[model_name]
    mdb.Model(model_name)

    # اگر پارت وجود دارد، حذف کن
    part_keys = mdb.models[model_name].parts.keys()
    if part_name in part_keys:
        del mdb.models[model_name].parts[part_name]

    # ساخت اسکچ پروفایل (مستطیل در صفحه X-Y)
    s = mdb.models[model_name].ConstrainedSketch(
        name='__profile__',
        sheetSize=200.0)
    s.rectangle(point1=(0.0, 0.0), point2=(L, total_thickness))

    # ساخت پارت 2D planar (نه 3D)
    p = mdb.models[model_name].Part(
        name=part_name,
        dimensionality=TWO_D_PLANAR,
        type=DEFORMABLE_BODY)
    p.BaseShell(sketch=s)

    print("[OK] Created 2D part '{}': L={} mm x t={:.4f} mm".format(
        part_name, L, total_thickness))
    print("     X = length (0 to {})".format(L))
    print("     Y = thickness (0 to {:.4f})".format(total_thickness))
    print("     Analysis: 2D {}".format(analysis_type))
    return p


