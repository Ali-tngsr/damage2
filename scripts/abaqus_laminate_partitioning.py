def partition_along_length(p, layup, L, L_gauge, rho):
    """
    پارتیشن‌بندی در جهت طول (X) با خطوط عمودی برای مسیرهای cohesive.
    فقط در لایه‌های 90° و در ناحیه gauge انجام می‌شود.
    """
    print("")
    print("--- Stage 3: Partitioning along length (cohesive column paths) ---")

    # محاسبه t90_total
    t90_total = 0.0
    for item in layup:
        if item[0] == 90:
            t90_total += item[1]
    n_cohesive = int(round(rho * t90_total / L_gauge))
    n_cohesive = max(n_cohesive, 1)

    print("  Total 90 thickness: {:.4f} mm".format(t90_total))
    print("  rho (crack saturation): {:.3f} cracks/mm".format(rho))
    print("  Gauge length: {:.3f} mm".format(L_gauge))
    print("  n_cohesive = rho x t90_total / L_gauge = {} x {:.4f} / {} = {}".format(
        rho, t90_total, L_gauge, n_cohesive))

    # محاسبه موقعیت‌های gauge
    x_gauge_start = (L - L_gauge) / 2.0
    x_gauge_end = x_gauge_start + L_gauge
    print("  Gauge region: X = {:.3f} to {:.3f} mm".format(x_gauge_start, x_gauge_end))

    # محاسبه Y-range لایه‌های 90°
    y_ranges_90 = []
    y_start = 0.0
    for item in layup:
        angle = item[0]
        t = item[1]
        y_end = y_start + t
        if angle == 90:
            y_ranges_90.append((y_start, y_end))
        y_start = y_end

    if n_cohesive == 0:
        print("  WARNING: n_cohesive = 0, skipping along-length partitioning")
        return 0

    # توزیع یکنواخت cohesive columns در gauge length
    dx = L_gauge / (n_cohesive + 1)

    n_partitions = 0
    for i in range(n_cohesive):
        x_partition = x_gauge_start + (i + 1) * dx

        # ساخت datum plane (YZPLANE offset در X = x_partition)
        # در 2D planar نیز DatumPlaneByPrincipalPlane استفاده می‌شود
        datum = p.DatumPlaneByPrincipalPlane(
            principalPlane=YZPLANE,
            offset=x_partition)

        # پیدا کردن faceهای مربوط به لایه‌های 90° در ناحیه gauge
        # FIX: استفاده از getByBoundingBox به جای حلقه روی faces
        # این روش بسیار سریع‌تر و قابل اعتمادتر است
        y_min_90 = min(yr[0] for yr in y_ranges_90)
        y_max_90 = max(yr[1] for yr in y_ranges_90)

        tol = 1e-6
        try:
            faces_to_partition = p.faces.getByBoundingBox(
                xMin=x_gauge_start - tol,
                yMin=y_min_90 - tol,
                zMin=-tol,
                xMax=x_gauge_end + tol,
                yMax=y_max_90 + tol,
                zMax=tol)
        except Exception:
            # Fallback: حلقه روی faces
            faces_to_partition = []
            for face in p.faces:
                try:
                    pt = face.pointOn[0]
                    cx = float(pt[0])
                    cy = float(pt[1])
                    for y_range in y_ranges_90:
                        y_min = y_range[0]
                        y_max = y_range[1]
                        if (y_min - 1e-6 <= cy <= y_max + 1e-6 and
                            x_gauge_start - 1e-6 <= cx <= x_gauge_end + 1e-6):
                            faces_to_partition.append(face)
                            break
                except Exception:
                    continue

        if len(faces_to_partition) > 0:
            try:
                p.PartitionFaceByDatumPlane(
                    datumPlane=p.datums[datum.id],
                    faces=faces_to_partition)
                n_partitions += 1
                print("  [{:2d}] Cohesive column {}/{} at X = {:.3f} mm ({} faces)".format(
                    n_partitions, i+1, n_cohesive, x_partition, len(faces_to_partition)))
            except Exception as e:
                print("  WARNING: Partition failed at X = {:.3f}: {}".format(x_partition, e))

    print("  -> Total cohesive column partitions: {}".format(n_partitions))
    return n_cohesive


