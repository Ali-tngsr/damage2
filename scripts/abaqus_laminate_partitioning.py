def build_layup(layup_type, n90, t0, t90):
    """ساخت دنباله لایه‌چینی از پایین به بالا."""
    layup = []
    if layup_type == 'symmetric':
        layup.append((0, t0))
        for i in range(n90):
            layup.append((90, t90))
        for i in range(n90):
            layup.append((90, t90))
        layup.append((0, t0))
    elif layup_type == 'asymmetric':
        layup.append((0, t0))
        for i in range(n90):
            layup.append((90, t90))
        layup.append((0, t0))
    else:
        raise ValueError("layup_type must be 'symmetric' or 'asymmetric'")
    return layup


