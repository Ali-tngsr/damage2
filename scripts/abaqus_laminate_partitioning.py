def create_face_sets(p, layup):
    """
    ساخت setهای وجهی (face sets) برای لایه‌های 0° و 90°.
    از getByBoundingBox استفاده می‌شود که در ABAQUS قابل اعتمادتر از findAt است.
    """
    print("")
    print("--- Stage 4: Creating face sets ---")

    # محاسبه Y-range هر لایه
    ply_info = []
    y_start = 0.0
    for i in range(len(layup)):
        angle = layup[i][0]
        t = layup[i][1]
        y_end = y_start + t
        ply_info.append((angle, y_start, y_end))
        y_start = y_end

    total_t = y_end

    # پیدا کردن Y-range لایه‌های 0° و 90°
    y_min_0 = total_t
    y_max_0 = 0.0
    y_min_90 = total_t
    y_max_90 = 0.0

    for ply in ply_info:
        angle = ply[0]
        y_min = ply[1]
        y_max = ply[2]
        if angle == 0:
            y_min_0 = min(y_min_0, y_min)
            y_max_0 = max(y_max_0, y_max)
        else:
            y_min_90 = min(y_min_90, y_min)
            y_max_90 = max(y_max_90, y_max)

    tol = 1e-6
    L_total = 0.0
    for item in layup:
        L_total = max(L_total, L)  # L از متغیر سراسری
    # FIX: استفاده از L سراسری
    L_total = L

    # ساخت Ply_0_Set با getByBoundingBox
    print("  Creating Ply_0_Set (0° plies)...")
    try:
        faces_0 = p.faces.getByBoundingBox(
            xMin=-tol, yMin=y_min_0 - tol, zMin=-tol,
            xMax=L_total + tol, yMax=y_max_0 + tol, zMax=tol)
        if len(faces_0) > 0:
            p.Set(faces=faces_0, name='Ply_0_Set')
            print("  [OK] Created 'Ply_0_Set' with {} faces".format(len(faces_0)))
        else:
            print("  WARNING: No 0° faces found")
    except Exception as e:
        print("  WARNING: getByBoundingBox failed for 0°: {}".format(e))

    # ساخت Ply_90_Set با getByBoundingBox
    print("  Creating Ply_90_Set (90° plies)...")
    try:
        faces_90 = p.faces.getByBoundingBox(
            xMin=-tol, yMin=y_min_90 - tol, zMin=-tol,
            xMax=L_total + tol, yMax=y_max_90 + tol, zMax=tol)
        if len(faces_90) > 0:
            p.Set(faces=faces_90, name='Ply_90_Set')
            print("  [OK] Created 'Ply_90_Set' with {} faces".format(len(faces_90)))
        else:
            print("  WARNING: No 90° faces found")
    except Exception as e:
        print("  WARNING: getByBoundingBox failed for 90°: {}".format(e))

    # ساخت set برای هر زیرسلول 90°
    print("")
    print("  Creating sub-cell sets for stochastic Vf assignment:")

    # برای هر face در 90°، یک set جداگانه بساز
    # FIX: استفاده از getByBoundingBox برای هر sub-cell به جای findAt
    cell_counter = 0

    for ply_idx, ply in enumerate(ply_info):
        if ply[0] != 90:
            continue

        y_ply_start = ply[1]
        y_ply_end = ply[2]
        t_ply = ply[2] - ply[1]
        dy = t_ply / n_cells_thickness

        for j in range(n_cells_thickness):
            y_cell_min = y_ply_start + j * dy
            y_cell_max = y_ply_start + (j + 1) * dy

            try:
                faces_cell = p.faces.getByBoundingBox(
                    xMin=-tol, yMin=y_cell_min - tol, zMin=-tol,
                    xMax=L_total + tol, yMax=y_cell_max + tol, zMax=tol)

                if len(faces_cell) > 0:
                    cell_counter += 1
                    set_name = 'Cell_90_{:03d}'.format(cell_counter)
                    p.Set(faces=faces_cell, name=set_name)
            except Exception:
                continue

    print("  [OK] Created {} individual face sets (Cell_90_001 to Cell_90_{:03d})".format(
        cell_counter, cell_counter))


