def partition_through_thickness(p, layup):
    """
    پارتیشن‌بندی در جهت ضخامت (Y) با خطوط افقی.
    NOTE: در ABAQUS 2D planar، DatumPlaneByPrincipalPlane استفاده می‌شود
    (نه DatumLineByPrincipalPlane) و PartitionFaceByDatumPlane برای پارتیشن.
    """
    print("")
    print("--- Stage 1: Partitioning through thickness (ply boundaries) ---")

    # محاسبه Y مرزهای لایه‌ها
    y_boundaries = []
    y_current = 0.0
    for i in range(len(layup) - 1):
        angle = layup[i][0]
        t = layup[i][1]
        y_current += t
        y_boundaries.append((y_current, i + 1, angle))

    n_partitions = 0
    for item in y_boundaries:
        y = item[0]
        ply_idx_above = item[1]
        angle_above = item[2]

        # ساخت datum plane (XZPLANE offset در Y = y)
        # در 2D planar نیز DatumPlaneByPrincipalPlane استفاده می‌شود
        datum = p.DatumPlaneByPrincipalPlane(
            principalPlane=XZPLANE,
            offset=y)

        # پارتیشن همه faces با این datum plane
        # FIX: استفاده از p.faces به جای p.faces[:]
        try:
            p.PartitionFaceByDatumPlane(
                datumPlane=p.datums[datum.id],
                faces=p.faces)
        except Exception:
            # Fallback: استفاده از face list
            face_list = []
            for f in p.faces:
                face_list.append(f)
            p.PartitionFaceByDatumPlane(
                datumPlane=p.datums[datum.id],
                faces=face_list)

        n_partitions += 1
        print("  [{:2d}] Partition at Y = {:.4f} mm (boundary: Ply {} = {} deg)".format(
            n_partitions, y, ply_idx_above, angle_above))

    print("  -> Total through-thickness partitions: {}".format(n_partitions))


