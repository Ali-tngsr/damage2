def partition_90_ply_subcells(p, layup, n_cells_thickness):
    """
    تقسیم هر لایه 90° به n_cells_thickness زیرسلول در جهت ضخامت.
    """
    print("")
    print("--- Stage 2: Partitioning 90 plies into {} sub-cells ---".format(n_cells_thickness))

    # محاسبه Y-range هر لایه
    ply_info = []
    y_start = 0.0
    for i in range(len(layup)):
        angle = layup[i][0]
        t = layup[i][1]
        y_end = y_start + t
        ply_info.append({
            'index': i + 1,
            'angle': angle,
            'y_start': y_start,
            'y_end': y_end,
            'thickness': t,
        })
        y_start = y_end

    n_partitions = 0
    for ply in ply_info:
        if ply['angle'] != 90:
            continue

        dy = ply['thickness'] / n_cells_thickness
        print("  Ply {} (90 deg, t = {:.3f} mm):".format(ply['index'], ply['thickness']))
        print("    Y range: {:.4f} to {:.4f} mm".format(ply['y_start'], ply['y_end']))
        print("    Sub-cell thickness: {:.4f} mm".format(dy))

        for j in range(1, n_cells_thickness):
            y_partition = ply['y_start'] + j * dy
            datum = p.DatumPlaneByPrincipalPlane(
                principalPlane=XZPLANE,
                offset=y_partition)
            # FIX: استفاده از p.faces به جای p.faces[:]
            try:
                p.PartitionFaceByDatumPlane(
                    datumPlane=p.datums[datum.id],
                    faces=p.faces)
            except Exception:
                face_list = []
                for f in p.faces:
                    face_list.append(f)
                p.PartitionFaceByDatumPlane(
                    datumPlane=p.datums[datum.id],
                    faces=face_list)
            n_partitions += 1
            print("    [{:2d}] Sub-cell partition at Y = {:.4f} mm".format(
                n_partitions, y_partition))

    print("  -> Total 90 sub-cell partitions: {}".format(n_partitions))


